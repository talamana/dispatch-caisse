-- Plats d'une commande, menus séparés : (cle, recette, nom, qte) — même logique que l'écran cuisine
create or replace function plats_commande(p_lignes jsonb) returns table (cle text, recette text, nom text, qte int)
language sql stable as $$
  with l as (
    select e ->> 'id' as id, coalesce(e ->> 'nom', '') as nom, coalesce((e ->> 'qte')::int, 0) as q
      from jsonb_array_elements(coalesce(p_lignes, '[]')) e
  ), elems as (
    select l.q * coalesce((c ->> 'qte')::int, 1) as q,
           coalesce(rc.id, rn.id) as recette,
           coalesce(rc.nom, rn.nom, c ->> 'nom', c ->> 'recette') as nom
      from l join articles a on a.id = l.id
      cross join lateral jsonb_array_elements(case when jsonb_array_length(a.composition) > 0 then a.composition
                                                   else jsonb_build_array(jsonb_build_object('nom', a.nom, 'qte', 1)) end) c
      left join recettes_cuisine rc on rc.id = c ->> 'recette'
      left join recettes_cuisine rn on c ->> 'recette' is null and norm(rn.nom) = norm(c ->> 'nom')
    union all
    select l.q, rn.id, coalesce(rn.nom, l.nom)
      from l left join articles a on a.id = l.id
      left join recettes_cuisine rn on norm(rn.nom) = norm(l.nom)
     where a.id is null
  )
  select coalesce(recette, 'x:' || norm(nom)), max(recette), max(nom), sum(q)::int
    from elems group by coalesce(recette, 'x:' || norm(nom))
$$;

-- ------------------------------------------------------- Calcul d'un panier de caisse --
-- p : {lignes:[{id, qte}], tarif, pourcentage (facultatif, remplace celui du tarif), rabais:{type, valeur, motif}}
create or replace function calcul_panier(p jsonb) returns jsonb
language plpgsql stable as $$
declare
  l jsonb; a articles; q numeric; ids text[] := '{}'; qtes jsonb := '{}'; lignes jsonb := '[]'; detail text := '';
  sous bigint := 0; t tarifs; pct numeric; libelle text; ajust bigint; base bigint; rab bigint := 0;
  r_type text; r_val numeric := 0; motif text; i text;
begin
  if jsonb_typeof(p -> 'lignes') is distinct from 'array' or jsonb_array_length(p -> 'lignes') = 0 then
    raise exception 'Commande vide.';
  end if;
  if jsonb_array_length(p -> 'lignes') > 100 then raise exception 'Commande trop longue.'; end if;
  for l in select value from jsonb_array_elements(p -> 'lignes') loop
    select * into a from articles where id = l ->> 'id' and actif;
    if not found then
      raise exception 'Article inconnu ou retiré de la carte : %', coalesce(l ->> 'nom', l ->> 'id');
    end if;
    if jsonb_typeof(l -> 'qte') is distinct from 'number' then raise exception 'Quantité invalide pour %.', a.nom; end if;
    q := (l ->> 'qte')::numeric;
    if q <> trunc(q) or q < 1 or q > 999 then raise exception 'Quantité invalide pour %.', a.nom; end if;
    if not (a.id = any (ids)) then ids := ids || a.id; end if;
    qtes := jsonb_set(qtes, array[a.id], to_jsonb(coalesce((qtes ->> a.id)::int, 0) + q::int));
  end loop;
  foreach i in array ids loop
    select * into a from articles where id = i;
    q := (qtes ->> i)::int;
    if q > 999 then raise exception 'Quantité invalide pour %.', a.nom; end if;
    lignes := lignes || jsonb_build_object('id', a.id, 'nom', a.nom, 'qte', q, 'prix', a.prix);
    sous := sous + a.prix * q;
    detail := detail || case when detail = '' then '' else ', ' end || q || '× ' || a.nom;
  end loop;

  if nullif(p ->> 'tarif', '') is null then
    select * into t from tarifs order by ordre, id limit 1;
  else
    select * into t from tarifs where id = p ->> 'tarif';
    if not found then raise exception 'Tarif inconnu : %', p ->> 'tarif'; end if;
  end if;
  pct := coalesce(t.pourcentage, 0); libelle := t.nom;
  if jsonb_typeof(p -> 'pourcentage') = 'number' then                -- remise / majoration réglée à la main
    pct := (p ->> 'pourcentage')::numeric;
    if pct < -100 or pct > 100 then raise exception 'Remise ou majoration impossible : % %%.', pct; end if;
    if pct is distinct from t.pourcentage then libelle := case when pct < 0 then 'Remise' else 'Majoration' end; end if;
  end if;
  ajust := arrondi(sous * pct / 100);
  base  := sous + ajust;

  if jsonb_typeof(p -> 'rabais') = 'object' then
    r_type := p -> 'rabais' ->> 'type';
    if r_type not in ('pourcent', 'montant') then raise exception 'Rabais illisible.'; end if;
    if jsonb_typeof(p -> 'rabais' -> 'valeur') is distinct from 'number' then raise exception 'Montant du rabais invalide.'; end if;
    r_val := (p -> 'rabais' ->> 'valeur')::numeric;
    if r_val < 0 then raise exception 'Montant du rabais invalide.'; end if;
    if r_type = 'pourcent' and r_val > 100 then raise exception 'Un rabais ne peut pas dépasser 100 %%.'; end if;
    rab := case when r_type = 'pourcent' then arrondi(base * r_val / 100) else least(arrondi(r_val * 100), base) end;
    rab := greatest(0, least(rab, base));
    motif := nullif(left(trim(coalesce(p -> 'rabais' ->> 'motif', '')), 100), '');
  end if;
  if rab = 0 then r_type := null; motif := null; end if;

  if ajust <> 0 then
    detail := detail || ' (' || libelle || ' ' || case when pct > 0 then '+' else '−' end || nombre_fr(abs(pct)) || ' %)';
  end if;
  if rab > 0 then
    detail := detail || ' — Rabais' || case when r_type = 'pourcent' then ' ' || nombre_fr(r_val) || ' %' else '' end
              || coalesce(' (' || motif || ')', '') || ' −' || fmt_argent(rab);
  end if;
  return jsonb_build_object('lignes', lignes, 'sous_total', sous, 'tarif', t.id, 'pourcentage', pct,
    'libelle_ajustement', libelle || ' ' || case when pct > 0 then '+' else '−' end || nombre_fr(abs(pct)) || ' %',
    'ajustement', ajust, 'rabais', rab, 'rabais_type', r_type, 'rabais_valeur', r_val, 'motif', motif,
    'libelle_rabais', 'Rabais' || case when r_type = 'pourcent' then ' ' || nombre_fr(r_val) || ' %' else '' end
                      || coalesce(' (' || motif || ')', ''),
    'total', base - rab, 'detail', detail);
end $$;

-- Lignes de devis / facture à partir d'un panier calculé
create or replace function lignes_document(c jsonb) returns jsonb
language sql stable as $$
  select coalesce((select jsonb_agg(jsonb_build_object('description', l ->> 'nom', 'quantite', (l ->> 'qte')::int,
                                                        'prix_unitaire', (l ->> 'prix')::bigint,
                                                        'total', (l ->> 'prix')::bigint * (l ->> 'qte')::int))
                     from jsonb_array_elements(c -> 'lignes') l), '[]')
      || case when (c ->> 'ajustement')::bigint <> 0 then jsonb_build_array(jsonb_build_object(
           'description', c ->> 'libelle_ajustement', 'quantite', 1,
           'prix_unitaire', (c ->> 'ajustement')::bigint, 'total', (c ->> 'ajustement')::bigint)) else '[]' end
      || case when (c ->> 'rabais')::bigint > 0 then jsonb_build_array(jsonb_build_object(
           'description', c ->> 'libelle_rabais', 'quantite', 1,
           'prix_unitaire', -(c ->> 'rabais')::bigint, 'total', -(c ->> 'rabais')::bigint)) else '[]' end
$$;

-- Client d'une commande : par id, sinon par nom ; créé si demandé (« creer_client ») et inconnu
create or replace function client_caisse(p jsonb) returns clients
language plpgsql as $$
declare cli clients; nom_c text := nullif(left(trim(coalesce(p ->> 'client', '')), 80), '');
        type_c text := coalesce(nullif(p ->> 'type_client', ''), 'particulier');
begin
  if type_c not in ('entreprise', 'auto_entreprise', 'micro_entreprise', 'association', 'parti_politique',
                    'syndicat', 'particulier', 'service_public') then
    raise exception 'Type de client inconnu : %', type_c;
  end if;
  if nullif(p ->> 'client_id', '') is not null then
    select * into cli from clients where id = (p ->> 'client_id')::bigint;
    if found then return cli; end if;
  end if;
  if nom_c is not null then
    select * into cli from clients where lower(trim(nom)) = lower(nom_c);
    if found then return cli; end if;
    if coalesce((p ->> 'creer_client')::boolean, false) then
      insert into clients (nom, type) values (nom_c, type_c) returning * into cli;
      return cli;
    end if;
  end if;
  return null;
end $$;

