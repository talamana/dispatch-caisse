do $$
declare t text;
begin
  foreach t in array array['reglages', 'tarifs', 'articles', 'recettes_cuisine', 'ingredients', 'clients', 'documents', 'recettes', 'depenses',
                           'dons', 'declarations', 'ventes', 'collaborateurs', 'missions', 'mission_collabs',
                           'paies', 'parts_patronales', 'taches', 'rdv', 'logements', 'stocks', 'mouvements_stock',
                           'reserve_plats', 'achats'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists gerant_tout on %I', t);
    execute format('create policy gerant_tout on %I for all to anon, authenticated using ((select est_gerant())) with check ((select est_gerant()))', t);
  end loop;
end $$;

