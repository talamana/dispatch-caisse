create or replace function prochain_numero(p_kind text) returns text
language plpgsql as $$
declare prefixe text := case p_kind when 'devis' then 'DEV' else 'FAC' end || '-'
                        || to_char(now() at time zone fuseau(), 'YYYY') || '-';
        n int;
begin
  perform exiger_gerant();
  select coalesce(max(nullif(regexp_replace(substring(numero from length(prefixe) + 1), '\D', '', 'g'), '')::int), 0) + 1
    into n from documents where numero like prefixe || '%';
  return prefixe || lpad(n::text, 4, '0');
end $$;

-- Crée un devis ou une facture ; le total est recalculé ici à partir des lignes
create or replace function creer_document(p jsonb) returns jsonb
language plpgsql as $$
declare k text := p ->> 'kind'; l jsonb; lignes jsonb := '[]'; total bigint := 0; q numeric; pu bigint; d documents;
begin
  perform exiger_gerant();
  if k not in ('devis', 'facture') then raise exception 'Type de document inconnu.'; end if;
  if jsonb_typeof(p -> 'lignes') is distinct from 'array' or jsonb_array_length(p -> 'lignes') = 0 then
    raise exception 'Ajoute au moins une ligne.';
  end if;
  for l in select value from jsonb_array_elements(p -> 'lignes') loop
    if coalesce(trim(l ->> 'description'), '') = '' then raise exception 'Une ligne n''a pas de description.'; end if;
    q := (l ->> 'quantite')::numeric; pu := (l ->> 'prix_unitaire')::bigint;
    if q is null or q <= 0 or pu is null or pu < 0 then raise exception 'Quantité ou prix invalide : %', l ->> 'description'; end if;
    lignes := lignes || jsonb_build_object('description', trim(l ->> 'description'), 'quantite', q,
                                           'prix_unitaire', pu, 'total', arrondi(q * pu));
    total := total + arrondi(q * pu);
  end loop;
  insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note)
  values (k, prochain_numero(k), nullif(p ->> 'client_id', '')::bigint, lignes, total,
          case k when 'devis' then 'en_attente' else 'impayee' end,
          nullif(p ->> 'echeance', '')::timestamptz, nullif(trim(coalesce(p ->> 'note', '')), ''))
  returning * into d;
  return to_jsonb(d);
end $$;

create or replace function convertir_devis(p_id bigint, p_echeance timestamptz default null) returns jsonb
language plpgsql as $$
declare dv documents; f documents;
begin
  perform exiger_gerant();
  select * into dv from documents where id = p_id and kind = 'devis' for update;
  if not found then raise exception 'Devis introuvable.'; end if;
  if dv.statut not in ('en_attente', 'accepte') then raise exception 'Ce devis ne peut plus être converti.'; end if;
  insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note, devis_id)
  values ('facture', prochain_numero('facture'), dv.client_id, dv.lignes, dv.total, 'impayee', p_echeance, dv.note, dv.id)
  returning * into f;
  update documents set statut = 'converti' where id = dv.id;
  return to_jsonb(f);
end $$;

create or replace function payer_facture(p_id bigint, p_quand timestamptz default now()) returns bigint
language plpgsql as $$
declare d documents; c clients; rid bigint;
begin
  perform exiger_gerant();
  select * into d from documents where id = p_id and kind = 'facture' for update;
  if not found then raise exception 'Facture introuvable.'; end if;
  if d.statut <> 'impayee' then raise exception 'Cette facture n''est pas en attente de paiement.'; end if;
  select * into c from clients where id = d.client_id;
  update documents set statut = 'payee', payee_le = coalesce(p_quand, now()) where id = p_id;
  insert into recettes (date, montant, client_id, type_client, description, facture_id)
  values (coalesce(p_quand, now()), d.total, d.client_id, coalesce(c.type, 'particulier'), 'Facture ' || d.numero, d.id)
  returning id into rid;
  return rid;
end $$;

-- Supprimer la recette d'une facture la remet « impayée »
create or replace function recette_supprimee() returns trigger
language plpgsql as $$
begin
  if old.facture_id is not null then
    update documents set statut = 'impayee', payee_le = null where id = old.facture_id and statut = 'payee';
  end if;
  return old;
end $$;
drop trigger if exists recette_supprimee on recettes;
create trigger recette_supprimee after delete on recettes for each row execute function recette_supprimee();

create or replace function terminer_mission(p_id bigint) returns int
language plpgsql as $$
declare m missions; n int;
begin
  perform exiger_gerant();
  select * into m from missions where id = p_id for update;
  if not found then raise exception 'Mission introuvable.'; end if;
  if m.statut <> 'planifiee' then raise exception 'Cette mission est déjà clôturée.'; end if;
  insert into paies (mission_id, collab_id, montant, date)
    select m.id, mc.collab_id, mc.remuneration, m.date from mission_collabs mc where mc.mission_id = m.id;
  get diagnostics n = row_count;
  update missions set statut = 'terminee' where id = m.id;
  return n;
end $$;

create or replace function valider_declaration(p_mois text) returns jsonb
language plpgsql as $$
declare b jsonb; d declarations;
begin
  perform exiger_gerant();
  if p_mois !~ '^\d{4}-\d{2}$' then raise exception 'Mois invalide.'; end if;
  if p_mois >= mois_courant() then raise exception 'Ce mois n''est pas terminé : on déclare le mois écoulé.'; end if;
  if exists (select 1 from declarations where mois = p_mois) then raise exception 'Ce mois est déjà déclaré.'; end if;
  b := bilan(p_mois);
  insert into declarations (mois, ca, benefice, impot)
  values (p_mois, (b ->> 'ca')::bigint, (b ->> 'benefice')::bigint, (b ->> 'impot')::bigint) returning * into d;
  return to_jsonb(d);
end $$;

-- Dons : plafond de l'arrêté (par don, par mois ou par an)
create or replace function verifier_plafond_dons() returns trigger
language plpgsql as $$
declare r reglages; deja bigint := 0; debut timestamptz; fin timestamptz;
begin
  select * into r from reglages where id = 1;
  if r.periode_dons = 'mois' then
    select * into debut, fin from bornes_mois(to_char(new.date at time zone fuseau(), 'YYYY-MM'));
  elsif r.periode_dons = 'annee' then
    debut := (date_trunc('year', new.date at time zone fuseau())) at time zone fuseau();
    fin := ((date_trunc('year', new.date at time zone fuseau())) + interval '1 year') at time zone fuseau();
  end if;
  if debut is not null then
    select coalesce(sum(montant), 0) into deja from dons
      where date >= debut and date < fin and id is distinct from new.id;
  end if;
  if deja + new.montant > r.plafond_dons::bigint * 100 then
    raise exception 'Plafond des dons dépassé : % maximum%. Déjà donné : %.',
      fmt_argent(r.plafond_dons::bigint * 100),
      case r.periode_dons when 'mois' then ' par mois' when 'annee' then ' par an' else ' par don' end,
      fmt_argent(deja);
  end if;
  return new;
end $$;
drop trigger if exists plafond_dons on dons;
create trigger plafond_dons before insert or update on dons for each row execute function verifier_plafond_dons();

