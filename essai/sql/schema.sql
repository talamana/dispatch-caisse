create or replace function arrondi(x numeric) returns bigint
language sql immutable as $$ select floor(x + 0.5)::bigint $$;

create or replace function fmt_argent(c bigint) returns text
language plpgsql immutable as $$
declare d bigint := abs(c) / 100; ct int := abs(c) % 100; t text;
begin
  t := regexp_replace(d::text, '(\d)(?=(\d{3})+$)', '\1 ', 'g');
  if ct > 0 then t := t || ',' || lpad(ct::text, 2, '0'); end if;
  return case when c < 0 then '-' else '' end || t || ' $';
end $$;

create or replace function nombre_fr(v numeric) returns text
language sql immutable as $$
  select replace(case when v = trunc(v) then trunc(v)::text
                      else rtrim(rtrim(v::text, '0'), '.') end, '.', ',')
$$;

create or replace function fuseau() returns text
language sql stable as $$ select coalesce((select fuseau from reglages where id = 1), 'Europe/Paris') $$;

-- Début et fin d'un mois « AAAA-MM » dans le fuseau du serveur RP
create or replace function bornes_mois(p_mois text, out debut timestamptz, out fin timestamptz)
language sql stable as $$
  select ((p_mois || '-01')::timestamp at time zone fuseau()),
         (((p_mois || '-01')::date + interval '1 month')::timestamp at time zone fuseau())
$$;

create or replace function mois_courant() returns text
language sql stable as $$ select to_char(now() at time zone fuseau(), 'YYYY-MM') $$;

create or replace function mois_precedent(p_mois text default null) returns text
language sql stable as $$
  select to_char((coalesce(p_mois, mois_courant()) || '-01')::date - interval '1 month', 'YYYY-MM')
$$;

-- Date limite de déclaration d'un mois (le jour_limite du mois suivant, 23h59)
create or replace function limite_declaration(p_mois text) returns timestamptz
language sql stable as $$
  select (((p_mois || '-01')::date + interval '1 month')::date
          + ((select jour_limite from reglages where id = 1) - 1)
          + time '23:59')::timestamp at time zone fuseau()
$$;

-- ----------------------------------------------------------------- Impôt --
create or replace function calcul_impot(benefice bigint, out impot bigint, out taux numeric)
language plpgsql stable as $$
declare r reglages; t jsonb; plafond numeric; tx numeric; bas numeric := 0; haut numeric; somme numeric := 0;
begin
  select * into r from reglages where id = 1;
  impot := 0; taux := 0;
  if benefice is null or benefice <= 0 then return; end if;
  for t in select value from jsonb_array_elements(r.tranches) loop
    plafond := case when jsonb_typeof(t -> 0) = 'null' then null else (t ->> 0)::numeric * 100 end;
    tx := (t ->> 1)::numeric;
    if r.mode_impot = 'tranches' then
      haut := case when plafond is null then benefice else least(benefice, plafond) end;
      if haut > bas then somme := somme + (haut - bas) * tx; end if;
      exit when plafond is null or benefice <= plafond;
      bas := plafond;
    elsif plafond is null or benefice <= plafond then
      impot := arrondi(benefice * tx); taux := tx; return;
    end if;
  end loop;
  impot := arrondi(somme);
  taux := round(impot::numeric / benefice, 4);
end $$;

-- ------------------------------------------------------------------ Bilan --
--  CA − dépenses déductibles = bénéfice → impôt (calculé AVANT paies d'intérimaires
--  et parts patronales, non déductibles) → résultat net.
create or replace function bilan(p_mois text default null) returns jsonb
language plpgsql stable as $$
declare
  m text := coalesce(p_mois, mois_courant()); b record;
  ca bigint; ca_types jsonb; ded bigint; ded_cat jsonb; nonded bigint; attente bigint;
  v_paies bigint; v_parts bigint; v_dons bigint; benef bigint; imp record; decl declarations;
begin
  perform exiger_gerant();
  select * into b from bornes_mois(m);
  select coalesce(sum(montant), 0) into ca from recettes where date >= b.debut and date < b.fin;
  select coalesce(jsonb_object_agg(type_client, s), '{}') into ca_types
    from (select type_client, sum(montant) s from recettes where date >= b.debut and date < b.fin group by 1) x;
  select coalesce(sum(montant) filter (where categorie <> 'non_deductible' and (categorie <> 'autre' or validee_mairie)), 0),
         coalesce(sum(montant) filter (where categorie = 'non_deductible'), 0),
         coalesce(sum(montant) filter (where categorie = 'autre' and not validee_mairie), 0)
    into ded, nonded, attente
    from depenses where date >= b.debut and date < b.fin;
  select coalesce(jsonb_object_agg(categorie, s), '{}') into ded_cat
    from (select categorie, sum(montant) s from depenses
          where date >= b.debut and date < b.fin and categorie <> 'non_deductible'
            and (categorie <> 'autre' or validee_mairie) group by 1) x;
  select coalesce(sum(montant), 0) into v_paies from paies where date >= b.debut and date < b.fin;
  select coalesce(sum(montant), 0) into v_parts from parts_patronales where date >= b.debut and date < b.fin;
  select coalesce(sum(montant), 0) into v_dons from dons where date >= b.debut and date < b.fin;
  benef := ca - ded;
  select * into imp from calcul_impot(benef);
  select * into decl from declarations where mois = m;
  return jsonb_build_object(
    'mois', m, 'ca', ca, 'ca_par_type', ca_types,
    'depenses_deductibles', ded, 'deductibles_par_categorie', ded_cat,
    'depenses_non_deductibles', nonded, 'depenses_en_attente', attente,
    'benefice', benef, 'impot', imp.impot, 'taux', imp.taux,
    'paies', v_paies, 'parts_patronales', v_parts, 'dons', v_dons,
    'resultat_net', benef - imp.impot - v_paies - v_parts - nonded - attente - v_dons,
    'limite_declaration', limite_declaration(m),
    'declaration', case when decl.mois is null then null else to_jsonb(decl) end);
end $$;

