-- ---------------------------------------------------------------- Réglages --
create table if not exists reglages (
  id            int primary key default 1 check (id = 1),
  entreprise    text   not null default 'Le Dispatch',
  sous_titre    text            default 'Diner — commandes à emporter',
  telephones    jsonb  not null default '[]',
  fuseau        text   not null default 'Europe/Paris',
  -- (plafond du bénéfice en $, taux) ; null = au-delà du dernier plafond (Art. III)
  tranches      jsonb  not null default '[[50000, 0], [150000, 0.20], [null, 0.30]]',
  -- forfait : le taux de la tranche atteinte s'applique à tout le bénéfice
  -- tranches : barème progressif
  mode_impot    text   not null default 'forfait' check (mode_impot in ('forfait', 'tranches')),
  jour_limite   int    not null default 15 check (jour_limite between 1 and 28),
  plafond_dons  int    not null default 5000,
  periode_dons  text   not null default 'mois' check (periode_dons in ('don', 'mois', 'annee'))
);
insert into reglages (id) values (1) on conflict (id) do nothing;

