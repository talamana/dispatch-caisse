-- Encaisser : comptant (recette tout de suite), à la semaine (client facturé le lundi) ou facture (« mode »: "facture")
create or replace function encaisser(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid text := nullif(trim(p ->> 'uid'), ''); v_old ventes; c jsonb; cli clients; payeur clients;
  nom_c text := nullif(left(trim(coalesce(p ->> 'client', '')), 80), '');
  type_c text := coalesce(nullif(p ->> 'type_client', ''), 'particulier');
  vendeur text := coalesce(nullif(left(trim(coalesce(p ->> 'vendeur', '')), 60), ''), 'Site');
  v_mode text := 'comptant'; v_id bigint; rec_id bigint; doc documents;
begin
  if v_uid is null then raise exception 'Commande sans identifiant.'; end if;
  select * into v_old from ventes where commande_uid = v_uid;
  if found then   -- même commande renvoyée (réseau coupé) : déjà comptée
    return jsonb_build_object('vente_id', v_old.id, 'total', v_old.total, 'mode', v_old.mode, 'doublon', true);
  end if;
  c := calcul_panier(p);
  cli := client_caisse(p || jsonb_build_object('creer_client', p ->> 'mode' = 'facture' or coalesce((p ->> 'creer_client')::boolean, false)));
  if cli.id is not null then nom_c := cli.nom; type_c := cli.type; end if;
  if type_c not in ('entreprise', 'auto_entreprise', 'micro_entreprise', 'association', 'parti_politique',
                    'syndicat', 'particulier', 'service_public') then
    raise exception 'Type de client inconnu : %', type_c;
  end if;

  if p ->> 'mode' = 'facture' then
    if cli.id is null then raise exception 'Pour une facture, indique le nom du client.'; end if;
    v_mode := 'facture';
  elsif cli.id is not null and cli.facturation_hebdo then
    v_mode := 'semaine';
    select * into payeur from clients where id = coalesce(cli.facture_a, cli.id);
  end if;

  if v_mode = 'comptant' then
    insert into recettes (montant, client_id, type_client, cree_par)
    values ((c ->> 'total')::bigint, cli.id, type_c, vendeur) returning id into rec_id;
  end if;
  insert into ventes (lignes, sous_total, ajustement, rabais, motif_rabais, total, tarif, pourcentage, client_id,
                      client_nom, type_client, vendeur, commande_uid, recette_id, mode, payeur_id)
  values (c -> 'lignes', (c ->> 'sous_total')::bigint, (c ->> 'ajustement')::bigint, (c ->> 'rabais')::bigint,
          c ->> 'motif', (c ->> 'total')::bigint, c ->> 'tarif', (c ->> 'pourcentage')::numeric, cli.id, nom_c, type_c,
          vendeur, v_uid, rec_id, v_mode, payeur.id)
  returning id into v_id;
  if rec_id is not null then
    update recettes set vente_id = v_id, description = left('Caisse n°' || v_id || ' — ' || (c ->> 'detail'), 500)
     where id = rec_id;
  end if;
  if v_mode = 'facture' then
    insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note)
    values ('facture', prochain_numero('facture'), coalesce(cli.facture_a, cli.id), lignes_document(c),
            (c ->> 'total')::bigint, 'impayee', now() + interval '7 days',
            left('Caisse n°' || v_id || coalesce(' — ' || cli.nom, '') || ' (' || vendeur || ')', 300))
    returning * into doc;
    update ventes set facture_id = doc.id where id = v_id;
  end if;
  return jsonb_build_object('vente_id', v_id, 'total', (c ->> 'total')::bigint, 'sous_total', (c ->> 'sous_total')::bigint,
    'ajustement', (c ->> 'ajustement')::bigint, 'rabais', (c ->> 'rabais')::bigint, 'mode', v_mode,
    'payeur', payeur.nom, 'client', nom_c, 'facture', doc.numero, 'doublon', false);
end $$;

-- Devis depuis la caisse (rien n'est encaissé ni envoyé en cuisine)
create or replace function caisse_devis(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare c jsonb; cli clients; d documents;
        vendeur text := coalesce(nullif(left(trim(coalesce(p ->> 'vendeur', '')), 60), ''), 'Site');
begin
  c := calcul_panier(p);
  cli := client_caisse(p || '{"creer_client": true}');
  if cli.id is null then raise exception 'Pour un devis, indique le nom du client.'; end if;
  insert into documents (kind, numero, client_id, lignes, total, statut, note)
  values ('devis', prochain_numero('devis'), cli.id, lignes_document(c), (c ->> 'total')::bigint, 'en_attente',
          left('Devis fait à la caisse (' || vendeur || ')', 300))
  returning * into d;
  return jsonb_build_object('id', d.id, 'numero', d.numero, 'total', d.total, 'client', cli.nom);
end $$;

-- ----------------------------------------------------------- Factures du lundi --
-- Ce qui reste à facturer : par payeur et par semaine (la semaine en cours n'est facturée que lundi prochain)
create or replace function a_facturer() returns jsonb
language plpgsql stable as $$
begin
  perform exiger_gerant();
  return coalesce((select jsonb_agg(x order by x.semaine desc, x.payeur) from (
    select p.id as payeur_id, p.nom as payeur, debut_semaine(v.date) as semaine,
           debut_semaine(v.date) < debut_semaine(now()) as a_faire,
           count(*) as n, sum(v.total) as total, jsonb_agg(distinct v.client_nom) as organismes
      from ventes v join clients p on p.id = v.payeur_id
     where v.mode = 'semaine' and v.facture_id is null
     group by p.id, p.nom, debut_semaine(v.date)) x), '[]');
end $$;

-- Crée une facture par payeur et par semaine terminée ; relancer ne crée rien en double
create or replace function facturer_semaines() returns jsonb
language plpgsql as $$
declare g record; v ventes; lignes jsonb; d documents; faites jsonb := '[]';
begin
  perform exiger_gerant();
  for g in select v2.payeur_id, debut_semaine(v2.date) as semaine
             from ventes v2
            where v2.mode = 'semaine' and v2.facture_id is null and v2.payeur_id is not null
              and v2.date < debut_semaine(now())
            group by 1, 2 order by 2, 1 loop
    lignes := '[]';
    for v in select * from ventes where mode = 'semaine' and facture_id is null and payeur_id = g.payeur_id
                and debut_semaine(date) = g.semaine order by date loop
      lignes := lignes || jsonb_build_object(
        'description', left('Commande n°' || v.id || ' du ' || date_fr(v.date) || coalesce(' — ' || v.client_nom, '') || ' : '
          || (select string_agg((l ->> 'qte') || '× ' || (l ->> 'nom'), ', ') from jsonb_array_elements(v.lignes) l)
          || case when v.ajustement <> 0 then ' (' || case when v.pourcentage > 0 then '+' else '−' end
                  || nombre_fr(abs(v.pourcentage)) || ' %)' else '' end
          || case when v.rabais > 0 then ' (rabais −' || fmt_argent(v.rabais) || ')' else '' end, 300),
        'quantite', 1, 'prix_unitaire', v.total, 'total', v.total);
    end loop;
    insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note)
    values ('facture', prochain_numero('facture'), g.payeur_id, lignes,
            (select sum((l ->> 'total')::bigint) from jsonb_array_elements(lignes) l), 'impayee',
            now() + interval '7 days',
            'Commandes de la semaine du ' || date_fr(g.semaine) || ' au '
              || to_char((g.semaine + interval '6 days') at time zone fuseau(), 'DD/MM/YYYY'))
    returning * into d;
    update ventes set facture_id = d.id
     where mode = 'semaine' and facture_id is null and payeur_id = g.payeur_id and debut_semaine(date) = g.semaine;
    faites := faites || jsonb_build_object('id', d.id, 'numero', d.numero, 'total', d.total,
                                           'client', (select nom from clients where id = g.payeur_id),
                                           'n', jsonb_array_length(lignes));
  end loop;
  return faites;
end $$;

-- Une facture annulée libère ses commandes de la semaine (elles repassent « à facturer »)
create or replace function facture_annulee() returns trigger
language plpgsql as $$
begin
  if new.kind = 'facture' and new.statut = 'annulee' and old.statut is distinct from 'annulee' then
    update ventes set facture_id = null where facture_id = new.id and mode = 'semaine';
  end if;
  return new;
end $$;
drop trigger if exists facture_annulee on documents;
create trigger facture_annulee after update of statut on documents for each row execute function facture_annulee();

-- Annuler une vente : refusé si elle est déjà sur une facture
create or replace function annuler_vente(p_id bigint) returns void
language plpgsql as $$
declare v ventes;
begin
  perform exiger_gerant();
  select * into v from ventes where id = p_id;
  if not found then raise exception 'Vente n°% introuvable.', p_id; end if;
  if v.facture_id is not null and exists (select 1 from documents where id = v.facture_id and statut <> 'annulee') then
    raise exception 'Cette vente est sur la facture %. Annule d''abord la facture.', (select numero from documents where id = v.facture_id);
  end if;
  delete from ventes where id = p_id;
  if v.recette_id is not null then delete from recettes where id = v.recette_id; end if;
end $$;

-- ------------------------------------------------------------------- Stock --
-- Ajoute (ou retire) une quantité dans un logement, avec trace
create or replace function bouger_stock(p_ingredient text, p_logement bigint, p_delta numeric, p_raison text,
                                        p_ref text default null, p_par text default null) returns void
language plpgsql as $$
begin
  if p_delta = 0 or p_logement is null then return; end if;
  insert into stocks (ingredient, logement_id, quantite) values (p_ingredient, p_logement, p_delta)
  on conflict (ingredient, logement_id) do update set quantite = stocks.quantite + excluded.quantite;
  insert into mouvements_stock (ingredient, logement_id, delta, raison, ref, par)
  values (p_ingredient, p_logement, p_delta, p_raison, p_ref, p_par);
end $$;

-- Retire du stock : d'abord le logement habituel de l'ingrédient, puis celui qui en a le plus
create or replace function retirer_stock(p_ingredient text, p_qte numeric, p_raison text, p_ref text default null,
                                         p_par text default null) returns jsonb
language plpgsql as $$
declare reste numeric := p_qte; s record; pris numeric; detail jsonb := '[]'; habituel bigint; premier bigint;
begin
  if p_qte <= 0 then return detail; end if;
  select logement_id into habituel from ingredients where nom = p_ingredient;
  for s in select st.logement_id, st.quantite from stocks st where st.ingredient = p_ingredient and st.quantite > 0
            order by (st.logement_id = habituel) desc nulls last, st.quantite desc loop
    exit when reste <= 0;
    pris := least(reste, s.quantite);
    perform bouger_stock(p_ingredient, s.logement_id, -pris, p_raison, p_ref, p_par);
    detail := detail || jsonb_build_object('logement_id', s.logement_id, 'qte', pris);
    reste := reste - pris;
  end loop;
  if reste > 0 then          -- pas assez en stock : on note le manque (stock négatif à vérifier)
    premier := coalesce(habituel, (select id from logements order by ordre, id limit 1));
    if premier is not null then
      perform bouger_stock(p_ingredient, premier, -reste, p_raison, p_ref, p_par);
      detail := detail || jsonb_build_object('logement_id', premier, 'qte', reste, 'manque', true);
    end if;
  end if;
  return detail;
end $$;

-- Inventaire : [{ingredient, logement_id, quantite}] -> quantités comptées ; renvoie les écarts
create or replace function inventaire(p jsonb, p_par text default null) returns jsonb
language plpgsql as $$
declare l jsonb; avant numeric; apres numeric; ecarts jsonb := '[]';
begin
  perform exiger_gerant();
  for l in select value from jsonb_array_elements(p) loop
    apres := (l ->> 'quantite')::numeric;
    if apres is null or apres < 0 then raise exception 'Quantité invalide pour %.', l ->> 'ingredient'; end if;
    select quantite into avant from stocks where ingredient = l ->> 'ingredient' and logement_id = (l ->> 'logement_id')::bigint;
    if coalesce(avant, 0) <> apres then
      perform bouger_stock(l ->> 'ingredient', (l ->> 'logement_id')::bigint, apres - coalesce(avant, 0), 'inventaire', null, p_par);
      ecarts := ecarts || jsonb_build_object('ingredient', l ->> 'ingredient', 'logement_id', (l ->> 'logement_id')::bigint,
                                             'avant', coalesce(avant, 0), 'apres', apres);
    end if;
  end loop;
  return ecarts;
end $$;

-- ------------------------------------------------------------------- Achats --
-- p : {fournisseur, lignes:[{nom, qte, prix}], logement_id, paiement, avance_par, date, note, par}
create or replace function enregistrer_achat(p jsonb) returns jsonb
language plpgsql as $$
declare l jsonb; lignes jsonb := '[]'; total bigint := 0; q numeric; pu bigint; nom_i text; a achats; dep_id bigint;
        f text := nullif(trim(coalesce(p ->> 'fournisseur', '')), ''); pay text := coalesce(p ->> 'paiement', 'semaine');
        quand timestamptz := coalesce(nullif(p ->> 'date', '')::timestamptz, now()); detail text := '';
begin
  perform exiger_gerant();
  if f is null then raise exception 'Indique le fournisseur.'; end if;
  if pay not in ('semaine', 'avance', 'entreprise') then raise exception 'Mode de paiement inconnu.'; end if;
  if pay = 'avance' and nullif(trim(coalesce(p ->> 'avance_par', '')), '') is null then
    raise exception 'Indique quel gérant a avancé l''argent.';
  end if;
  if jsonb_typeof(p -> 'lignes') is distinct from 'array' or jsonb_array_length(p -> 'lignes') = 0 then
    raise exception 'Ajoute au moins un ingrédient.';
  end if;
  for l in select value from jsonb_array_elements(p -> 'lignes') loop
    nom_i := nullif(trim(coalesce(l ->> 'nom', '')), '');
    q := (l ->> 'qte')::numeric; pu := coalesce((l ->> 'prix')::bigint, 0);
    if nom_i is null or q is null or q <= 0 or pu < 0 then raise exception 'Ligne invalide : %', coalesce(nom_i, '?'); end if;
    nom_i := nom_ingredient(nom_i);
    insert into ingredients (nom) values (nom_i) on conflict (nom) do nothing;
    lignes := lignes || jsonb_build_object('nom', nom_i, 'qte', q, 'prix', pu, 'total', arrondi(q * pu));
    total := total + arrondi(q * pu);
    detail := detail || case when detail = '' then '' else ', ' end || nombre_fr(q) || '× ' || nom_i;
  end loop;
  if pay in ('avance', 'entreprise') and total > 0 then
    insert into depenses (date, montant, categorie, fournisseur, description, avance_par)
    values (quand, total, 'matieres_premieres', f, left('Achat : ' || detail, 500),
            case when pay = 'avance' then trim(p ->> 'avance_par') end)
    returning id into dep_id;
  end if;
  insert into achats (date, fournisseur, lignes, total, logement_id, paiement, avance_par, paye_le, depense_id, note, par)
  values (quand, f, lignes, total, nullif(p ->> 'logement_id', '')::bigint, pay,
          case when pay = 'avance' then trim(p ->> 'avance_par') end,
          case when pay <> 'semaine' then quand end, dep_id, nullif(trim(coalesce(p ->> 'note', '')), ''), p ->> 'par')
  returning * into a;
  if a.logement_id is not null then
    for l in select value from jsonb_array_elements(lignes) loop
      perform bouger_stock(l ->> 'nom', a.logement_id, (l ->> 'qte')::numeric, 'achat', 'Achat n°' || a.id || ' — ' || f, p ->> 'par');
    end loop;
  end if;
  return to_jsonb(a);
end $$;

-- Ce qu'on doit à chaque fournisseur (payable maintenant = achats des semaines terminées)
create or replace function dettes_fournisseurs() returns jsonb
language plpgsql stable as $$
begin
  perform exiger_gerant();
  return coalesce((select jsonb_agg(x order by x.fournisseur) from (
    select fournisseur, count(*) as n, sum(total) as total,
           coalesce(sum(total) filter (where date < debut_semaine(now())), 0) as du_maintenant,
           coalesce(sum(total) filter (where date >= debut_semaine(now())), 0) as semaine_en_cours,
           min(date) as depuis
      from achats where paiement = 'semaine' and paye_le is null group by fournisseur) x), '[]');
end $$;

-- Paie un fournisseur : les achats des semaines terminées (ou tout, p_tout) deviennent une dépense
create or replace function payer_fournisseur(p_fournisseur text, p_tout boolean default false) returns jsonb
language plpgsql as $$
declare tot bigint; n int; d1 timestamptz; d2 timestamptz; dep_id bigint; limite timestamptz := debut_semaine(now());
begin
  perform exiger_gerant();
  select sum(total), count(*), min(date), max(date) into tot, n, d1, d2 from achats
   where fournisseur = p_fournisseur and paiement = 'semaine' and paye_le is null and (p_tout or date < limite);
  if coalesce(n, 0) = 0 then raise exception 'Rien à payer à % pour l''instant.', p_fournisseur; end if;
  if tot > 0 then
    insert into depenses (montant, categorie, fournisseur, description)
    values (tot, 'matieres_premieres', p_fournisseur,
            'Achats ' || p_fournisseur || ' du ' || date_fr(d1) || ' au ' || date_fr(d2) || ' (' || n || ' livraison' || case when n > 1 then 's' else '' end || ')')
    returning id into dep_id;
  end if;
  update achats set paye_le = now(), depense_id = dep_id
   where fournisseur = p_fournisseur and paiement = 'semaine' and paye_le is null and (p_tout or date < limite);
  return jsonb_build_object('total', coalesce(tot, 0), 'n', n);
end $$;

-- Argent avancé par les gérants et pas encore remboursé
create or replace function avances_dues() returns jsonb
language plpgsql stable as $$
begin
  perform exiger_gerant();
  return coalesce((select jsonb_agg(x order by x.gerant) from (
    select avance_par as gerant, count(*) as n, sum(montant) as total, min(date) as depuis,
           jsonb_agg(jsonb_build_object('id', id, 'date', date, 'montant', montant, 'fournisseur', fournisseur,
                                        'description', description) order by date) as depenses
      from depenses where avance_par is not null and rembourse_le is null group by avance_par) x), '[]');
end $$;

create or replace function rembourser_avances(p_gerant text, p_ids bigint[] default null) returns bigint
language plpgsql as $$
declare tot bigint;
begin
  perform exiger_gerant();
  update depenses set rembourse_le = now()
   where avance_par = p_gerant and rembourse_le is null and (p_ids is null or id = any (p_ids));
  select coalesce(sum(montant), 0) into tot from depenses where avance_par = p_gerant and rembourse_le >= now() - interval '1 second';
  return tot;
end $$;

-- ------------------------------------------------------------- Cuisine (v2) --
-- Portions encore à préparer pour une commande : {cle: qte restante}
create or replace function reste_commande(v ventes) returns table (cle text, recette text, nom text, qte int, faits int)
language sql stable as $$
  select p.cle, p.recette, p.nom, p.qte,
         least(p.qte, case when jsonb_typeof(v.cuisine_faits) = 'array'
                           then case when v.cuisine_faits ? p.cle then p.qte else 0 end
                           else coalesce((v.cuisine_faits ->> p.cle)::int, 0) end)
    from plats_commande(v.lignes) p
$$;

-- Donne les portions en réserve aux commandes les plus anciennes ; renvoie [{vente, n}]
create or replace function servir_reserve(p_recette text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare dispo int; v ventes; r record; donne int; faits jsonb; allocs jsonb := '[]'; complet boolean;
begin
  select portions into dispo from reserve_plats where recette_id = p_recette for update;
  dispo := coalesce(dispo, 0);
  for v in select * from ventes where cuisine <> 'servie' and date > now() - interval '3 days' order by date, id for update loop
    exit when dispo <= 0;
    select * into r from reste_commande(v) x where x.cle = p_recette;
    if r.cle is null or r.faits >= r.qte then continue; end if;
    donne := least(dispo, r.qte - r.faits);
    faits := case when jsonb_typeof(v.cuisine_faits) = 'object' then v.cuisine_faits
                  else (select coalesce(jsonb_object_agg(x.cle, x.faits), '{}') from reste_commande(v) x where x.faits > 0) end;
    faits := jsonb_set(faits, array[p_recette], to_jsonb(r.faits + donne));
    select bool_and(x.cle like 'x:%' or coalesce((faits ->> x.cle)::int, 0) >= x.qte) into complet from plats_commande(v.lignes) x;
    update ventes set cuisine_faits = faits, cuisine_le = now(),
                      cuisine = case when complet then 'prete' when cuisine = 'a_faire' then 'en_cours' else cuisine end
     where id = v.id;
    dispo := dispo - donne;
    allocs := allocs || jsonb_build_object('vente', v.id, 'n', donne);
  end loop;
  insert into reserve_plats (recette_id, portions) values (p_recette, dispo)
  on conflict (recette_id) do update set portions = excluded.portions;
  return allocs;
end $$;

-- Lance des cuissons : prend les ingrédients (stock) et les sous-recettes (réserve), ajoute les portions
-- à la réserve puis les donne aux commandes en attente. Renvoie {portions, donnees:[{vente, n}], reserve, pris}
create or replace function cuisiner(p_recette text, p_fois int default 1, p_par text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare r recettes_cuisine; i jsonb; sous recettes_cuisine; besoin int; dispo int; pris jsonb := '[]'; allocs jsonb;
        nom_i text; reserve int;
begin
  if p_fois is null or p_fois < 1 or p_fois > 50 then raise exception 'Nombre de cuissons invalide.'; end if;
  select * into r from recettes_cuisine where id = p_recette;
  if not found then raise exception 'Recette inconnue.'; end if;
  -- 1. les sous-recettes doivent être prêtes (ex. Crêpe pour Crêpe au chocolat)
  for i in select value from jsonb_array_elements(r.ingredients) loop
    select * into sous from recettes_cuisine where norm(nom) = norm(i ->> 'nom') and id <> r.id;
    if sous.id is not null then
      besoin := coalesce((i ->> 'qte')::int, 1) * p_fois;
      select portions into dispo from reserve_plats where recette_id = sous.id;
      if coalesce(dispo, 0) < besoin then
        raise exception 'Il faut d''abord préparer % × % (% prête%).', besoin - coalesce(dispo, 0), sous.nom,
          coalesce(dispo, 0), case when coalesce(dispo, 0) > 1 then 's' else '' end;
      end if;
    end if;
  end loop;
  -- 2. on prend les sous-recettes et les ingrédients
  for i in select value from jsonb_array_elements(r.ingredients) loop
    select * into sous from recettes_cuisine where norm(nom) = norm(i ->> 'nom') and id <> r.id;
    besoin := coalesce((i ->> 'qte')::int, 1) * p_fois;
    if sous.id is not null then
      update reserve_plats set portions = portions - besoin where recette_id = sous.id;
      pris := pris || jsonb_build_object('nom', sous.nom, 'qte', besoin, 'reserve', true);
    else
      nom_i := nom_ingredient(i ->> 'nom');
      insert into ingredients (nom) values (nom_i) on conflict (nom) do nothing;
      pris := pris || jsonb_build_object('nom', nom_i, 'qte', besoin,
                'depuis', retirer_stock(nom_i, besoin, 'cuisson', r.nom || ' ×' || p_fois, p_par));
    end if;
  end loop;
  -- 3. portions en réserve, puis aux commandes
  insert into reserve_plats (recette_id, portions) values (r.id, r.produit * p_fois)
  on conflict (recette_id) do update set portions = reserve_plats.portions + excluded.portions;
  allocs := servir_reserve(r.id);
  select portions into reserve from reserve_plats where recette_id = r.id;
  return jsonb_build_object('portions', r.produit * p_fois, 'donnees', allocs, 'reserve', coalesce(reserve, 0), 'pris', pris);
end $$;

-- Fabrique un ingrédient combiné (ex. Pâte = Farine + …) : retire les composants, ajoute le résultat au stock
create or replace function fabriquer(p_ingredient text, p_fois int default 1, p_par text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare ing ingredients; c jsonb; dest bigint;
begin
  if p_fois is null or p_fois < 1 or p_fois > 50 then raise exception 'Nombre invalide.'; end if;
  select * into ing from ingredients where nom = p_ingredient;
  if not found or jsonb_array_length(ing.composition) = 0 then raise exception '% n''est pas un ingrédient combiné.', p_ingredient; end if;
  for c in select value from jsonb_array_elements(ing.composition) loop
    perform retirer_stock(c ->> 'nom', coalesce((c ->> 'qte')::numeric, 1) * p_fois, 'fabrication', ing.nom || ' ×' || p_fois, p_par);
  end loop;
  dest := coalesce(ing.logement_id, (select id from logements order by ordre, id limit 1));
  perform bouger_stock(ing.nom, dest, ing.produit * p_fois, 'fabrication', ing.nom || ' ×' || p_fois, p_par);
  return jsonb_build_object('qte', ing.produit * p_fois, 'logement_id', dest);
end $$;

-- Marque des plats à la main (sans cuisson enregistrée) : p_faits = {cle: n} ; ou change l'état
create or replace function cuisine_etat(p_id bigint, p_etat text default null, p_faits jsonb default null)
returns void language plpgsql security definer set search_path = public as $$
declare v ventes; complet boolean;
begin
  if p_etat is not null and p_etat not in ('a_faire', 'en_cours', 'prete', 'servie') then
    raise exception 'État de cuisine inconnu : %', p_etat;
  end if;
  if p_faits is not null and jsonb_typeof(p_faits) not in ('object', 'array') then raise exception 'Liste de plats illisible.'; end if;
  update ventes set cuisine_faits = coalesce(p_faits, cuisine_faits), cuisine_le = now() where id = p_id returning * into v;
  if not found then raise exception 'Commande introuvable.'; end if;
  if p_etat is null and p_faits is not null then
    select bool_and(x.cle like 'x:%' or x.faits >= x.qte) into complet from reste_commande(v) x;
    p_etat := case when complet then 'prete' when v.cuisine = 'a_faire' then 'en_cours'
                   when v.cuisine = 'prete' then 'en_cours' else null end;
  end if;
  if p_etat is not null then update ventes set cuisine = p_etat where id = p_id; end if;
end $$;

-- Écran cuisine : commandes en cours (avec le reste à faire par plat)
create or replace function cuisine_commandes() returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', v.id, 'date', v.date, 'vendeur', v.vendeur, 'client', v.client_nom, 'lignes', v.lignes,
      'etat', v.cuisine, 'etat_le', v.cuisine_le, 'mode', v.mode,
      'plats', (select coalesce(jsonb_agg(jsonb_build_object('cle', x.cle, 'recette', x.recette, 'nom', x.nom,
                                                             'qte', x.qte, 'faits', x.faits) order by x.nom), '[]')
                  from reste_commande(v) x)) order by v.date, v.id), '[]')
    from ventes v where v.cuisine <> 'servie' and v.date > now() - interval '3 days'
$$;

create or replace function cuisine() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'commandes', cuisine_commandes(),
    'articles', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'nom', a.nom, 'emoji', a.emoji,
        'composition', a.composition)) from articles a), '[]'),
    'recettes', coalesce((select jsonb_agg(to_jsonb(r) order by r.nom) from recettes_cuisine r where r.actif), '[]'),
    'ingredients', coalesce((select jsonb_agg(to_jsonb(i) order by i.nom) from ingredients i), '[]'),
    'logements', coalesce((select jsonb_agg(to_jsonb(l) order by l.ordre, l.id) from logements l), '[]'),
    'stocks', coalesce((select jsonb_agg(to_jsonb(s)) from stocks s where s.quantite <> 0), '[]'),
    'reserve', coalesce((select jsonb_object_agg(recette_id, portions) from reserve_plats where portions > 0), '{}'))
$$;

-- ------------------------------------------------------- Tableau de bord (v2) --
create or replace function tableau_de_bord() returns jsonb
language plpgsql stable as $$
declare
  m text := mois_courant(); prec text := mois_precedent(); b_prec jsonb; activite_prec boolean;
  jour_debut timestamptz := date_trunc('day', now() at time zone fuseau()) at time zone fuseau();
  r jsonb; bp record;
begin
  perform exiger_gerant();
  select * into bp from bornes_mois(prec);
  activite_prec := exists (select 1 from recettes where date >= bp.debut and date < bp.fin)
                or exists (select 1 from depenses where date >= bp.debut and date < bp.fin);
  b_prec := bilan(prec);
  r := jsonb_build_object(
    'mois', bilan(m),
    'declaration_precedente', jsonb_build_object(
        'mois', prec, 'faite', (b_prec -> 'declaration') is not null and b_prec -> 'declaration' <> 'null'::jsonb,
        'activite', activite_prec, 'impot', b_prec -> 'impot', 'limite', limite_declaration(prec),
        'en_retard', now() > limite_declaration(prec)),
    'factures', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(total), 0),
                        'en_retard', count(*) filter (where echeance < now()))
                 from documents where kind = 'facture' and statut = 'impayee'),
    'devis', (select jsonb_build_object('attente', count(*) filter (where statut = 'en_attente'),
                     'acceptes', count(*) filter (where statut = 'accepte'),
                     'total_acceptes', coalesce(sum(total) filter (where statut = 'accepte'), 0))
              from documents where kind = 'devis'),
    'a_facturer', (select jsonb_build_object(
                      'n_payeurs', count(distinct payeur_id) filter (where date < debut_semaine(now())),
                      'total', coalesce(sum(total) filter (where date < debut_semaine(now())), 0),
                      'semaine_en_cours', coalesce(sum(total) filter (where date >= debut_semaine(now())), 0))
                   from ventes where mode = 'semaine' and facture_id is null),
    'dettes_fournisseurs', (select jsonb_build_object('total', coalesce(sum(total), 0),
                               'du_maintenant', coalesce(sum(total) filter (where date < debut_semaine(now())), 0))
                            from achats where paiement = 'semaine' and paye_le is null),
    'avances', (select jsonb_build_object('n', count(distinct avance_par), 'total', coalesce(sum(montant), 0))
                from depenses where avance_par is not null and rembourse_le is null),
    'stock_bas', (select count(*) from ingredients i where i.stock_base is not null and i.stock_base >
                    coalesce((select sum(quantite) from stocks s where s.ingredient = i.nom), 0)),
    'paies_dues', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(montant), 0))
                   from paies where not payee),
    'ventes_jour', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(total), 0))
                    from ventes where date >= jour_debut),
    'depenses_mairie', (select count(*) from depenses where categorie = 'autre' and not validee_mairie),
    'taches_ouvertes', (select count(*) from taches where statut = 'ouverte'),
    'taches_en_retard', (select count(*) from taches where statut = 'ouverte' and echeance < now()),
    'rdv_a_venir', (select coalesce(jsonb_agg(x order by x.quand), '[]') from
                     (select r2.id, r2.titre, r2.quand, r2.lieu, c.nom as client from rdv r2
                      left join clients c on c.id = r2.client_id
                      where r2.statut = 'prevu' and r2.quand >= now() order by r2.quand limit 5) x),
    'genere_le', now());
  return r;
end $$;

