create or replace function carte() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'entreprise', r.entreprise, 'sous_titre', r.sous_titre, 'telephones', r.telephones,
    'tarifs', coalesce((select jsonb_agg(to_jsonb(t) order by t.ordre, t.id) from tarifs t), '[]'),
    'articles', coalesce((select jsonb_agg(jsonb_build_object(
                   'id', a.id, 'nom', a.nom, 'prix', a.prix, 'emoji', a.emoji, 'contenu', a.contenu,
                   'categorie', a.categorie, 'compact', a.compact) order by a.ordre, a.nom)
                 from articles a where a.actif), '[]'))
  from reglages r where r.id = 1
$$;


