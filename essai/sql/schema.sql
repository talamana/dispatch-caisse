                                              where v.cuisine_faits ? x.cle), '{}')
 where jsonb_typeof(v.cuisine_faits) = 'array';

-- « Lait » = « Pot de lait entier » (même produit) : on fusionne
do $$
declare cible text := 'Pot de lait entier'; source text;
begin
  for source in select nom from ingredients where norm(nom) in ('lait', 'pot de lait', 'lait entier') and nom <> cible loop
    insert into ingredients (nom) values (cible) on conflict (nom) do nothing;
    update ingredients set
      prix_superette   = coalesce(prix_superette,   (select prix_superette   from ingredients where nom = source)),
      prix_maraicher   = coalesce(prix_maraicher,   (select prix_maraicher   from ingredients where nom = source)),
      prix_fournisseur = coalesce(prix_fournisseur, (select prix_fournisseur from ingredients where nom = source)),
      stock_base       = coalesce(stock_base,       (select stock_base       from ingredients where nom = source))
     where nom = cible;
    insert into stocks (ingredient, logement_id, quantite)
    select cible, logement_id, quantite from stocks where ingredient = source
    on conflict (ingredient, logement_id) do update set quantite = stocks.quantite + excluded.quantite;
    update ingredients set composition = (
        select coalesce(jsonb_agg(case when e ->> 'nom' = source then jsonb_set(e, '{nom}', to_jsonb(cible)) else e end), '[]')
          from jsonb_array_elements(composition) e)
     where composition @> jsonb_build_array(jsonb_build_object('nom', source));
    delete from ingredients where nom = source;
  end loop;
end $$;

-- =============================================================================
--  Code gérant (sans compte utilisateur)
--  Le site échange le code contre un jeton de session, envoyé ensuite dans l'en-tête « x-gerant ».
--  Premier passage sur le site : il demande de CHOISIR le code. Code oublié : exécuter
--  « delete from acces; » dans Supabase > SQL Editor, puis rouvrir le site pour en choisir un nouveau.
-- =============================================================================
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;

create table if not exists acces (
  id         int primary key default 1 check (id = 1),
  code_hash  text not null,
  modifie_le timestamptz not null default now()
);
create table if not exists sessions_gerant (
  jeton   text primary key,
  cree_le timestamptz not null default now(),
  expire  timestamptz not null
);
alter table acces enable row level security;            -- aucune politique : illisible depuis le site
alter table sessions_gerant enable row level security;

create or replace function jeton_requete() returns text
language sql stable as $$
  select nullif(coalesce(nullif(current_setting('request.headers', true), ''), '{}')::json ->> 'x-gerant', '')
$$;

create or replace function jeton_valide(p_jeton text) returns boolean
language sql stable security definer set search_path = public as $$
  select p_jeton is not null and exists (select 1 from sessions_gerant where jeton = p_jeton and expire > now())
$$;

-- Gérant = jeton valide ; le bot (clé secrète) et l'éditeur SQL passent toujours.
create or replace function est_gerant() returns boolean
language sql stable as $$
  select current_user <> 'anon' or jeton_valide(jeton_requete())
$$;

create or replace function exiger_gerant() returns void
language plpgsql stable as $$
begin
  if not est_gerant() then
    raise exception 'Espace gérant : entre le code gérant.' using errcode = '42501';
  end if;
end $$;

create or replace function etat_acces() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('code_defini', exists (select 1 from acces), 'gerant', jeton_valide(jeton_requete()))
$$;

create or replace function connexion(p_code text) returns text
language plpgsql security definer set search_path = public, extensions as $$
declare h text; j text;
begin
  select code_hash into h from acces where id = 1;
  if h is null then raise exception 'Aucun code gérant pour l''instant : choisis-en un.'; end if;
  if crypt(coalesce(p_code, ''), h) <> h then
    perform pg_sleep(0.4);                                -- freine les essais en rafale
    raise exception 'Code gérant incorrect.';
  end if;
  delete from sessions_gerant where expire < now();
  j := encode(gen_random_bytes(32), 'hex');
  insert into sessions_gerant (jeton, expire) values (j, now() + interval '30 days');
  return j;
end $$;

-- Premier code (si aucun n'existe) ou changement de code (gérant connecté) : déconnecte les autres appareils
create or replace function definir_code(p_code text) returns text
language plpgsql security definer set search_path = public, extensions as $$
begin
  if length(trim(coalesce(p_code, ''))) < 4 then
    raise exception 'Le code doit faire au moins 4 caractères.';
  end if;
  if exists (select 1 from acces) and not jeton_valide(jeton_requete())
     and coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb ->> 'role' is distinct from 'service_role' then
    raise exception 'Un code gérant existe déjà : connecte-toi pour le changer.' using errcode = '42501';
  end if;
  insert into acces (id, code_hash) values (1, crypt(p_code, gen_salt('bf')))
    on conflict (id) do update set code_hash = excluded.code_hash, modifie_le = now();
  delete from sessions_gerant;
  return connexion(p_code);
end $$;

create or replace function deconnexion() returns void
language sql security definer set search_path = public as $$
  delete from sessions_gerant where jeton = jeton_requete()
$$;

