-- =============================================================================
--  Fonctions utilitaires
-- =============================================================================
create or replace function arrondi(x numeric) returns bigint
language sql immutable as $$ select floor(x + 0.5)::bigint $$;

create or replace function fmt_argent(c bigint) returns text
language plpgsql immutable as $$
declare d bigint := abs(c) / 100; ct int := abs(c) % 100; t text;
begin
  t := regexp_replace(d::text, '(\d)(?=(\d{3})+$)', '\1 ', 'g');
  if ct > 0 then t := t || ',' || lpad(ct::text, 2, '0'); end if;
  return case when c < 0 then '-' else '' end || t || ' $';
end $$;

create or replace function nombre_fr(v numeric) returns text
language sql immutable as $$
  select replace(case when v = trunc(v) then trunc(v)::text
                      else rtrim(rtrim(v::text, '0'), '.') end, '.', ',')
$$;

create or replace function fuseau() returns text
language sql stable as $$ select coalesce((select fuseau from reglages where id = 1), 'Europe/Paris') $$;

-- Début et fin d'un mois « AAAA-MM » dans le fuseau du serveur RP
create or replace function bornes_mois(p_mois text, out debut timestamptz, out fin timestamptz)
language sql stable as $$
  select ((p_mois || '-01')::timestamp at time zone fuseau()),
         (((p_mois || '-01')::date + interval '1 month')::timestamp at time zone fuseau())
$$;

create or replace function mois_courant() returns text
language sql stable as $$ select to_char(now() at time zone fuseau(), 'YYYY-MM') $$;

create or replace function mois_precedent(p_mois text default null) returns text
language sql stable as $$
  select to_char((coalesce(p_mois, mois_courant()) || '-01')::date - interval '1 month', 'YYYY-MM')
$$;

-- Date limite de déclaration d'un mois (le jour_limite du mois suivant, 23h59)
create or replace function limite_declaration(p_mois text) returns timestamptz
language sql stable as $$
  select (((p_mois || '-01')::date + interval '1 month')::date
          + ((select jour_limite from reglages where id = 1) - 1)
          + time '23:59')::timestamp at time zone fuseau()
$$;

-- ----------------------------------------------------------------- Impôt --
create or replace function calcul_impot(benefice bigint, out impot bigint, out taux numeric)
language plpgsql stable as $$
declare r reglages; t jsonb; plafond numeric; tx numeric; bas numeric := 0; haut numeric; somme numeric := 0;
begin
  select * into r from reglages where id = 1;
  impot := 0; taux := 0;
  if benefice is null or benefice <= 0 then return; end if;
  for t in select value from jsonb_array_elements(r.tranches) loop
    plafond := case when jsonb_typeof(t -> 0) = 'null' then null else (t ->> 0)::numeric * 100 end;
    tx := (t ->> 1)::numeric;
    if r.mode_impot = 'tranches' then
      haut := case when plafond is null then benefice else least(benefice, plafond) end;
      if haut > bas then somme := somme + (haut - bas) * tx; end if;
      exit when plafond is null or benefice <= plafond;
      bas := plafond;
    elsif plafond is null or benefice <= plafond then
      impot := arrondi(benefice * tx); taux := tx; return;
    end if;
  end loop;
  impot := arrondi(somme);
  taux := round(impot::numeric / benefice, 4);
end $$;

-- ------------------------------------------------------------------ Bilan --
--  CA − dépenses déductibles = bénéfice → impôt (calculé AVANT paies d'intérimaires
--  et parts patronales, non déductibles) → résultat net.
create or replace function bilan(p_mois text default null) returns jsonb
language plpgsql stable as $$
declare
  m text := coalesce(p_mois, mois_courant()); b record;
  ca bigint; ca_types jsonb; ded bigint; ded_cat jsonb; nonded bigint; attente bigint;
  v_paies bigint; v_parts bigint; v_dons bigint; benef bigint; imp record; decl declarations;
begin
  perform exiger_gerant();
  select * into b from bornes_mois(m);
  select coalesce(sum(montant), 0) into ca from recettes where date >= b.debut and date < b.fin;
  select coalesce(jsonb_object_agg(type_client, s), '{}') into ca_types
    from (select type_client, sum(montant) s from recettes where date >= b.debut and date < b.fin group by 1) x;
  select coalesce(sum(montant) filter (where categorie <> 'non_deductible' and (categorie <> 'autre' or validee_mairie)), 0),
         coalesce(sum(montant) filter (where categorie = 'non_deductible'), 0),
         coalesce(sum(montant) filter (where categorie = 'autre' and not validee_mairie), 0)
    into ded, nonded, attente
    from depenses where date >= b.debut and date < b.fin;
  select coalesce(jsonb_object_agg(categorie, s), '{}') into ded_cat
    from (select categorie, sum(montant) s from depenses
          where date >= b.debut and date < b.fin and categorie <> 'non_deductible'
            and (categorie <> 'autre' or validee_mairie) group by 1) x;
  select coalesce(sum(montant), 0) into v_paies from paies where date >= b.debut and date < b.fin;
  select coalesce(sum(montant), 0) into v_parts from parts_patronales where date >= b.debut and date < b.fin;
  select coalesce(sum(montant), 0) into v_dons from dons where date >= b.debut and date < b.fin;
  benef := ca - ded;
  select * into imp from calcul_impot(benef);
  select * into decl from declarations where mois = m;
  return jsonb_build_object(
    'mois', m, 'ca', ca, 'ca_par_type', ca_types,
    'depenses_deductibles', ded, 'deductibles_par_categorie', ded_cat,
    'depenses_non_deductibles', nonded, 'depenses_en_attente', attente,
    'benefice', benef, 'impot', imp.impot, 'taux', imp.taux,
    'paies', v_paies, 'parts_patronales', v_parts, 'dons', v_dons,
    'resultat_net', benef - imp.impot - v_paies - v_parts - nonded - attente - v_dons,
    'limite_declaration', limite_declaration(m),
    'declaration', case when decl.mois is null then null else to_jsonb(decl) end);
end $$;

-- ------------------------------------------------- Tableau de bord (site + bot)
create or replace function tableau_de_bord() returns jsonb
language plpgsql stable as $$
declare
  m text := mois_courant(); prec text := mois_precedent(); b_prec jsonb; activite_prec boolean;
  jour_debut timestamptz := date_trunc('day', now() at time zone fuseau()) at time zone fuseau();
  r jsonb; bp record;
begin
  perform exiger_gerant();
  select * into bp from bornes_mois(prec);
  activite_prec := exists (select 1 from recettes where date >= bp.debut and date < bp.fin)
                or exists (select 1 from depenses where date >= bp.debut and date < bp.fin);
  b_prec := bilan(prec);
  r := jsonb_build_object(
    'mois', bilan(m),
    'declaration_precedente', jsonb_build_object(
        'mois', prec, 'faite', (b_prec -> 'declaration') is not null and b_prec -> 'declaration' <> 'null'::jsonb,
        'activite', activite_prec, 'impot', b_prec -> 'impot', 'limite', limite_declaration(prec),
        'en_retard', now() > limite_declaration(prec)),
    'factures', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(total), 0),
                        'en_retard', count(*) filter (where echeance < now()))
                 from documents where kind = 'facture' and statut = 'impayee'),
    'devis', (select jsonb_build_object('attente', count(*) filter (where statut = 'en_attente'),
                     'acceptes', count(*) filter (where statut = 'accepte'),
                     'total_acceptes', coalesce(sum(total) filter (where statut = 'accepte'), 0))
              from documents where kind = 'devis'),
    'paies_dues', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(montant), 0))
                   from paies where not payee),
    'ventes_jour', (select jsonb_build_object('n', count(*), 'total', coalesce(sum(total), 0))
                    from ventes where date >= jour_debut),
    'depenses_mairie', (select count(*) from depenses where categorie = 'autre' and not validee_mairie),
    'taches_ouvertes', (select count(*) from taches where statut = 'ouverte'),
    'taches_en_retard', (select count(*) from taches where statut = 'ouverte' and echeance < now()),
    'rdv_a_venir', (select coalesce(jsonb_agg(x order by x.quand), '[]') from
                     (select r2.id, r2.titre, r2.quand, r2.lieu, c.nom as client from rdv r2
                      left join clients c on c.id = r2.client_id
                      where r2.statut = 'prevu' and r2.quand >= now() order by r2.quand limit 5) x),
    'genere_le', now());
  return r;
end $$;

-- =============================================================================
--  Caisse (accessible sans code) — les prix viennent TOUJOURS de la table articles
-- =============================================================================
create or replace function carte() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'entreprise', r.entreprise, 'sous_titre', r.sous_titre, 'telephones', r.telephones,
    'tarifs', coalesce((select jsonb_agg(to_jsonb(t) order by t.ordre, t.id) from tarifs t), '[]'),
    'articles', coalesce((select jsonb_agg(jsonb_build_object(
                   'id', a.id, 'nom', a.nom, 'prix', a.prix, 'emoji', a.emoji, 'contenu', a.contenu,
                   'categorie', a.categorie, 'compact', a.compact) order by a.ordre, a.nom)
                 from articles a where a.actif), '[]'))
  from reglages r where r.id = 1
$$;

create or replace function encaisser(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_uid   text := nullif(trim(p ->> 'uid'), '');
  v_old   ventes;
  l       jsonb;
  a       articles;
  q       numeric;
  ids     text[] := '{}';
  qtes    jsonb := '{}';
  lignes  jsonb := '[]';
  detail  text := '';
  sous    bigint := 0;
  t       tarifs;
  ajust   bigint;
  base    bigint;
  rab     bigint := 0;
  r_type  text;
  r_val   numeric := 0;
  motif   text;
  type_c  text := coalesce(nullif(p ->> 'type_client', ''), 'particulier');
  nom_c   text := nullif(left(trim(coalesce(p ->> 'client', '')), 80), '');
  vendeur text := coalesce(nullif(left(trim(coalesce(p ->> 'vendeur', '')), 60), ''), 'Site');
  cli     clients;
  v_id    bigint;
  rec_id  bigint;
  descr   text;
  i       text;
begin
  if v_uid is null then raise exception 'Commande sans identifiant.'; end if;
  select * into v_old from ventes where commande_uid = v_uid;
  if found then   -- même commande renvoyée (réseau coupé) : déjà comptée
    return jsonb_build_object('vente_id', v_old.id, 'total', v_old.total, 'doublon', true);
  end if;
  if jsonb_typeof(p -> 'lignes') is distinct from 'array' or jsonb_array_length(p -> 'lignes') = 0 then
    raise exception 'Commande vide.';
  end if;
  if jsonb_array_length(p -> 'lignes') > 100 then raise exception 'Commande trop longue.'; end if;

  for l in select value from jsonb_array_elements(p -> 'lignes') loop
    select * into a from articles where id = l ->> 'id' and actif;
    if not found then
      raise exception 'Article inconnu ou retiré de la carte : %', coalesce(l ->> 'nom', l ->> 'id');
    end if;
    if jsonb_typeof(l -> 'qte') is distinct from 'number' then raise exception 'Quantité invalide pour %.', a.nom; end if;
    q := (l ->> 'qte')::numeric;
    if q <> trunc(q) or q < 1 or q > 999 then raise exception 'Quantité invalide pour %.', a.nom; end if;
    if not (a.id = any (ids)) then ids := ids || a.id; end if;
    qtes := jsonb_set(qtes, array[a.id], to_jsonb(coalesce((qtes ->> a.id)::int, 0) + q::int));
  end loop;

  foreach i in array ids loop
    select * into a from articles where id = i;
    q := (qtes ->> i)::int;
    if q > 999 then raise exception 'Quantité invalide pour %.', a.nom; end if;
    lignes := lignes || jsonb_build_object('id', a.id, 'nom', a.nom, 'qte', q, 'prix', a.prix);
    sous := sous + a.prix * q;
    detail := detail || case when detail = '' then '' else ', ' end || q || '× ' || a.nom;
  end loop;

  if nullif(p ->> 'tarif', '') is null then
    select * into t from tarifs order by ordre, id limit 1;
  else
    select * into t from tarifs where id = p ->> 'tarif';
    if not found then raise exception 'Tarif inconnu : %', p ->> 'tarif'; end if;
  end if;
  ajust := case when t.id is null then 0 else arrondi(sous * t.pourcentage / 100) end;
  base  := sous + ajust;

  if jsonb_typeof(p -> 'rabais') = 'object' then
    r_type := p -> 'rabais' ->> 'type';
    if r_type not in ('pourcent', 'montant') then raise exception 'Rabais illisible.'; end if;
    if jsonb_typeof(p -> 'rabais' -> 'valeur') is distinct from 'number' then raise exception 'Montant du rabais invalide.'; end if;
    r_val := (p -> 'rabais' ->> 'valeur')::numeric;
    if r_val < 0 then raise exception 'Montant du rabais invalide.'; end if;
    if r_type = 'pourcent' and r_val > 100 then raise exception 'Un rabais ne peut pas dépasser 100 %%.'; end if;
    rab := case when r_type = 'pourcent' then arrondi(base * r_val / 100) else least(arrondi(r_val * 100), base) end;
    rab := greatest(0, least(rab, base));
    motif := nullif(left(trim(coalesce(p -> 'rabais' ->> 'motif', '')), 100), '');
  end if;
  if rab = 0 then r_type := null; motif := null; end if;

  if type_c not in ('entreprise', 'auto_entreprise', 'micro_entreprise', 'association',
                    'parti_politique', 'syndicat', 'particulier') then
    raise exception 'Type de client inconnu : %', type_c;
  end if;
  if nom_c is not null then
    select * into cli from clients where lower(trim(nom)) = lower(nom_c);
    if found then nom_c := cli.nom; type_c := cli.type; end if;
  end if;

  if ajust <> 0 then
    detail := detail || ' (' || t.nom || ' ' || case when t.pourcentage > 0 then '+' else '−' end
              || nombre_fr(abs(t.pourcentage)) || ' %)';
  end if;
  if rab > 0 then
    detail := detail || ' — Rabais' || case when r_type = 'pourcent' then ' ' || nombre_fr(r_val) || ' %' else '' end
              || coalesce(' (' || motif || ')', '') || ' −' || fmt_argent(rab);
  end if;

  insert into recettes (montant, client_id, type_client, cree_par)
  values (base - rab, cli.id, type_c, vendeur) returning id into rec_id;
  insert into ventes (lignes, sous_total, ajustement, rabais, motif_rabais, total, tarif, client_id,
                      client_nom, type_client, vendeur, commande_uid, recette_id)
  values (lignes, sous, ajust, rab, motif, base - rab, t.id, cli.id, nom_c, type_c, vendeur, v_uid, rec_id)
  returning id into v_id;
  descr := left('Caisse n°' || v_id || ' — ' || detail, 500);
  update recettes set vente_id = v_id, description = descr where id = rec_id;

  return jsonb_build_object('vente_id', v_id, 'total', base - rab, 'sous_total', sous,
                            'ajustement', ajust, 'rabais', rab, 'doublon', false);
end $$;

-- =============================================================================
--  Actions du gérant (s'exécutent avec les droits de l'utilisateur connecté)
-- =============================================================================
create or replace function annuler_vente(p_id bigint) returns void
language plpgsql as $$
declare v ventes;
begin
  perform exiger_gerant();
  select * into v from ventes where id = p_id;
  if not found then raise exception 'Vente n°% introuvable.', p_id; end if;
  delete from ventes where id = p_id;
  if v.recette_id is not null then delete from recettes where id = v.recette_id; end if;
end $$;

create or replace function prochain_numero(p_kind text) returns text
language plpgsql as $$
declare prefixe text := case p_kind when 'devis' then 'DEV' else 'FAC' end || '-'
                        || to_char(now() at time zone fuseau(), 'YYYY') || '-';
        n int;
begin
  perform exiger_gerant();
  select coalesce(max(nullif(regexp_replace(substring(numero from length(prefixe) + 1), '\D', '', 'g'), '')::int), 0) + 1
    into n from documents where numero like prefixe || '%';
  return prefixe || lpad(n::text, 4, '0');
end $$;

-- Crée un devis ou une facture ; le total est recalculé ici à partir des lignes
create or replace function creer_document(p jsonb) returns jsonb
language plpgsql as $$
declare k text := p ->> 'kind'; l jsonb; lignes jsonb := '[]'; total bigint := 0; q numeric; pu bigint; d documents;
begin
  perform exiger_gerant();
  if k not in ('devis', 'facture') then raise exception 'Type de document inconnu.'; end if;
  if jsonb_typeof(p -> 'lignes') is distinct from 'array' or jsonb_array_length(p -> 'lignes') = 0 then
    raise exception 'Ajoute au moins une ligne.';
  end if;
  for l in select value from jsonb_array_elements(p -> 'lignes') loop
    if coalesce(trim(l ->> 'description'), '') = '' then raise exception 'Une ligne n''a pas de description.'; end if;
    q := (l ->> 'quantite')::numeric; pu := (l ->> 'prix_unitaire')::bigint;
    if q is null or q <= 0 or pu is null or pu < 0 then raise exception 'Quantité ou prix invalide : %', l ->> 'description'; end if;
    lignes := lignes || jsonb_build_object('description', trim(l ->> 'description'), 'quantite', q,
                                           'prix_unitaire', pu, 'total', arrondi(q * pu));
    total := total + arrondi(q * pu);
  end loop;
  insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note)
  values (k, prochain_numero(k), nullif(p ->> 'client_id', '')::bigint, lignes, total,
          case k when 'devis' then 'en_attente' else 'impayee' end,
          nullif(p ->> 'echeance', '')::timestamptz, nullif(trim(coalesce(p ->> 'note', '')), ''))
  returning * into d;
  return to_jsonb(d);
end $$;

create or replace function convertir_devis(p_id bigint, p_echeance timestamptz default null) returns jsonb
language plpgsql as $$
declare dv documents; f documents;
begin
  perform exiger_gerant();
  select * into dv from documents where id = p_id and kind = 'devis' for update;
  if not found then raise exception 'Devis introuvable.'; end if;
  if dv.statut not in ('en_attente', 'accepte') then raise exception 'Ce devis ne peut plus être converti.'; end if;
  insert into documents (kind, numero, client_id, lignes, total, statut, echeance, note, devis_id)
  values ('facture', prochain_numero('facture'), dv.client_id, dv.lignes, dv.total, 'impayee', p_echeance, dv.note, dv.id)
  returning * into f;
  update documents set statut = 'converti' where id = dv.id;
  return to_jsonb(f);
end $$;

create or replace function payer_facture(p_id bigint, p_quand timestamptz default now()) returns bigint
language plpgsql as $$
declare d documents; c clients; rid bigint;
begin
  perform exiger_gerant();
  select * into d from documents where id = p_id and kind = 'facture' for update;
  if not found then raise exception 'Facture introuvable.'; end if;
  if d.statut <> 'impayee' then raise exception 'Cette facture n''est pas en attente de paiement.'; end if;
  select * into c from clients where id = d.client_id;
  update documents set statut = 'payee', payee_le = coalesce(p_quand, now()) where id = p_id;
  insert into recettes (date, montant, client_id, type_client, description, facture_id)
  values (coalesce(p_quand, now()), d.total, d.client_id, coalesce(c.type, 'particulier'), 'Facture ' || d.numero, d.id)
  returning id into rid;
  return rid;
end $$;

-- Supprimer la recette d'une facture la remet « impayée »
create or replace function recette_supprimee() returns trigger
language plpgsql as $$
begin
  if old.facture_id is not null then
    update documents set statut = 'impayee', payee_le = null where id = old.facture_id and statut = 'payee';
  end if;
  return old;
end $$;
drop trigger if exists recette_supprimee on recettes;
create trigger recette_supprimee after delete on recettes for each row execute function recette_supprimee();

create or replace function terminer_mission(p_id bigint) returns int
language plpgsql as $$
declare m missions; n int;
begin
  perform exiger_gerant();
  select * into m from missions where id = p_id for update;
  if not found then raise exception 'Mission introuvable.'; end if;
  if m.statut <> 'planifiee' then raise exception 'Cette mission est déjà clôturée.'; end if;
  insert into paies (mission_id, collab_id, montant, date)
    select m.id, mc.collab_id, mc.remuneration, m.date from mission_collabs mc where mc.mission_id = m.id;
  get diagnostics n = row_count;
  update missions set statut = 'terminee' where id = m.id;
  return n;
end $$;

create or replace function valider_declaration(p_mois text) returns jsonb
language plpgsql as $$
declare b jsonb; d declarations;
begin
  perform exiger_gerant();
  if p_mois !~ '^\d{4}-\d{2}$' then raise exception 'Mois invalide.'; end if;
  if p_mois >= mois_courant() then raise exception 'Ce mois n''est pas terminé : on déclare le mois écoulé.'; end if;
  if exists (select 1 from declarations where mois = p_mois) then raise exception 'Ce mois est déjà déclaré.'; end if;
  b := bilan(p_mois);
  insert into declarations (mois, ca, benefice, impot)
  values (p_mois, (b ->> 'ca')::bigint, (b ->> 'benefice')::bigint, (b ->> 'impot')::bigint) returning * into d;
  return to_jsonb(d);
end $$;

-- Dons : plafond de l'arrêté (par don, par mois ou par an)
create or replace function verifier_plafond_dons() returns trigger
language plpgsql as $$
declare r reglages; deja bigint := 0; debut timestamptz; fin timestamptz;
begin
  select * into r from reglages where id = 1;
  if r.periode_dons = 'mois' then
    select * into debut, fin from bornes_mois(to_char(new.date at time zone fuseau(), 'YYYY-MM'));
  elsif r.periode_dons = 'annee' then
    debut := (date_trunc('year', new.date at time zone fuseau())) at time zone fuseau();
    fin := ((date_trunc('year', new.date at time zone fuseau())) + interval '1 year') at time zone fuseau();
  end if;
  if debut is not null then
    select coalesce(sum(montant), 0) into deja from dons
      where date >= debut and date < fin and id is distinct from new.id;
  end if;
  if deja + new.montant > r.plafond_dons::bigint * 100 then
    raise exception 'Plafond des dons dépassé : % maximum%. Déjà donné : %.',
      fmt_argent(r.plafond_dons::bigint * 100),
      case r.periode_dons when 'mois' then ' par mois' when 'annee' then ' par an' else ' par don' end,
      fmt_argent(deja);
  end if;
  return new;
end $$;
drop trigger if exists plafond_dons on dons;
create trigger plafond_dons before insert or update on dons for each row execute function verifier_plafond_dons();

