-- =============================================================================
--  LE DISPATCH — base de données (Supabase / PostgreSQL)
--  À coller UNE fois dans Supabase : SQL Editor > New query > coller > Run.
--  Le script peut être relancé sans risque : il ne supprime aucune donnée.
--
--  Sécurité (Row Level Security) :
--    - visiteur anonyme (caisse du site) : peut SEULEMENT lire la carte et encaisser
--      via la fonction encaisser(), qui recalcule elle-même tous les prix ;
--    - gérant connecté (code gérant) : accès complet ;
--    - clé « service_role » (bot Discord) : accès complet, elle ne sort jamais du PC.
--  Montants en centimes ($ × 100). Dates en heure de Paris (réglable dans reglages).
